// Loading the wasm modules: one instance of each module a page, shared by
// every chart of its types (REQ-LOAD-010), found through web/pkg/modules.js
// (REQ-MANIFEST-010). Memory views are made only after the call that returns
// their address (REQ-DATA-060, REQ-WASM-030), and a chart whose call trapped
// refuses every later call (REQ-WASM-040).

import type { Manifest, WasmChart, WasmModule } from "./api.ts";

/** A loaded module: its exports and its memory. */
export interface Loaded {
  readonly name: string;
  readonly module: WasmModule;
  readonly memory: WebAssembly.Memory;
}

let manifestPromise: Promise<Manifest> | null = null;
const loaded = new Map<string, Promise<Loaded>>();
/** How many times each module was instantiated: a test reads it (REQ-LOAD-010). */
export const instantiations = new Map<string, number>();

/**
 * Uses `manifest` instead of web/pkg/modules.js: the Node tests point the
 * shell at a debug build this way (REQ-TEST-020). Modules already loaded stay.
 */
export function setManifest(manifest: Manifest | Promise<Manifest>): void {
  manifestPromise = Promise.resolve(manifest);
}

/** The manifest, imported once. */
export function manifest(): Promise<Manifest> {
  if (!manifestPromise) {
    // Generated by `mise run build:wasm`; absent before the first build.
    // @ts-ignore: the module and its types exist only after a build
    const p: Promise<unknown> = import("../pkg/modules.js");
    manifestPromise = p.then((m) => m as Manifest);
    manifestPromise.catch(() => {
      manifestPromise = null; // try again on the next call (REQ-LOAD-010)
    });
  }
  return manifestPromise;
}

/** The module that plays `type`, or null when none does (REQ-MANIFEST-020). */
export function moduleOf(type: string, m: Pick<Manifest, "modules" | "fallback">): string | null {
  return Object.hasOwn(m.modules, type) ? (m.modules[type] ?? null) : m.fallback;
}

/** The error a type no module plays rejects with (REQ-LOAD-010, REQ-WASM-020). */
export function noChart(type: string): Error {
  return new Error(`there is no chart named "${type}"`);
}

const isNode = (): boolean => typeof (globalThis as { process?: { versions?: { node?: string } } }).process?.versions?.node === "string";

/** What to pass wasm-bindgen's init: nothing in a browser (the glue fetches its own file), the bytes in Node. */
async function initInput(name: string): Promise<{ module_or_path: unknown } | undefined> {
  if (!isNode()) return undefined;
  const url = new URL(`../pkg/${name}/glyphplot_bg.wasm`, import.meta.url);
  if (url.protocol !== "file:") return undefined;
  const fsName = "node:fs/promises";
  const fs = (await import(/* @vite-ignore */ fsName)) as { readFile(u: URL): Promise<Uint8Array> };
  return { module_or_path: await fs.readFile(url) };
}

/**
 * Module `name`, imported and instantiated at most once a page and shared
 * (REQ-LOAD-010). A failed load is forgotten, so the next call tries again.
 */
export function loadModule(name: string): Promise<Loaded> {
  let p = loaded.get(name);
  if (!p) {
    p = (async () => {
      const m = await manifest();
      const importer = Object.hasOwn(m.imports, name) ? m.imports[name] : undefined;
      if (!importer) throw new Error(`there is no module named "${name}"`);
      const module = (await importer()) as WasmModule;
      const out = await module.default(await initInput(name));
      instantiations.set(name, (instantiations.get(name) ?? 0) + 1);
      module.start?.();
      return { name, module, memory: out.memory };
    })();
    loaded.set(name, p);
    p.catch(() => {
      if (loaded.get(name) === p) loaded.delete(name);
    });
  }
  return p;
}

/** The module that plays `type`, loaded; rejects with `there is no chart named "<type>"` when none does. */
export async function loadFor(type: string): Promise<Loaded> {
  const m = await manifest();
  const name = moduleOf(type, m);
  if (name === null) throw noChart(type);
  return loadModule(name);
}

/** Whether `e` is a trap: a panic under `panic = "abort"`, or any other wasm runtime error. */
export function isTrap(e: unknown): boolean {
  return typeof WebAssembly !== "undefined" && e instanceof WebAssembly.RuntimeError;
}

/** The message of a thrown value, wasm-bindgen's strings included. */
export function messageOf(e: unknown): string {
  if (e instanceof Error) return e.message;
  if (typeof e === "string") return e;
  try {
    return JSON.stringify(e) ?? String(e);
  } catch {
    return String(e);
  }
}

/** The grid of the last frame, as views made after the frame (REQ-WASM-030). */
export interface GridViews {
  cols: number;
  rows: number;
  /** Code points, row by row. */
  cells: Uint32Array;
  /** Ink palette indices. */
  colors: Uint8Array;
  /** Back palette indices; 255 is none. */
  backs: Uint8Array;
}

/**
 * One wasm chart with its module's memory. Every call goes through
 * {@link Guarded.call}: after a trap the chart is dead and every later call
 * throws (REQ-WASM-040). Views over memory are made only from addresses a
 * call just returned, reading `memory.buffer` afterwards (REQ-DATA-060).
 */
export class Guarded {
  readonly raw: WasmChart;
  readonly loaded: Loaded;
  #dead: string | null = null;
  #freed = false;

  constructor(raw: WasmChart, loaded: Loaded) {
    this.raw = raw;
    this.loaded = loaded;
  }

  /** Why the chart refuses calls, or null while it works. */
  get dead(): string | null {
    return this.#freed ? "the chart was freed" : this.#dead;
  }

  /** Runs `f` on the chart; a trap kills the chart and is rethrown. */
  call<T>(f: (c: WasmChart) => T): T {
    const dead = this.dead;
    if (dead !== null) throw new Error(`glyphplot: ${dead}`);
    try {
      return f(this.raw);
    } catch (e) {
      if (isTrap(e)) {
        this.#dead = `the chart stopped after a trap (${messageOf(e)})`;
        console.error(`glyphplot: a chart trapped and was stopped: ${messageOf(e)}`);
      }
      throw e;
    }
  }

  /** Reserves column `i` and returns a fresh view over it. */
  reserveF64(i: number, n: number): Float64Array {
    const ptr = this.call((c) => c.reserve_column(i, 0, n));
    return new Float64Array(this.loaded.memory.buffer, ptr, n);
  }

  /** Reserves category column `i` and returns a fresh view over it. */
  reserveU32(i: number, n: number): Uint32Array {
    const ptr = this.call((c) => c.reserve_column(i, 1, n));
    return new Uint32Array(this.loaded.memory.buffer, ptr, n);
  }

  /** Views over the grid, made now; valid until the next call that may allocate. */
  grid(): GridViews {
    return this.call((c) => {
      const cols = c.cols();
      const rows = c.rows();
      const n = cols * rows;
      const cp = c.cells_ptr();
      const kp = c.colors_ptr();
      const bp = c.backs_ptr();
      const buffer = this.loaded.memory.buffer; // read after the addresses
      return {
        cols,
        rows,
        cells: new Uint32Array(buffer, cp, n),
        colors: new Uint8Array(buffer, kp, n),
        backs: new Uint8Array(buffer, bp, n),
      };
    });
  }

  /** Frees the chart once; a dead chart is freed too, ignoring a second trap. */
  free(): void {
    if (this.#freed) return;
    this.#freed = true;
    try {
      this.raw.free();
    } catch {
      // A trapped chart may fail to free; the instance lives on.
    }
  }
}

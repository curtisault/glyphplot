//! The manifest `mise run build:wasm` builds from and writes beside the
//! modules (REQ-BUILD-030, `spec/schemas/manifest.schema.json`).
//!
//! ```sh
//! cargo run -q -p glyphplot --example manifest -- families      # one family a line
//! cargo run -q -p glyphplot --example manifest -- write <dir>   # modules.js, modules.d.ts, budgets.json
//! ```
//!
//! No chart is registered yet, so `charts` and `modules` are empty; Phase 2
//! fills them from each chart's meta (REQ-MANIFEST-010).

use std::path::Path;
use std::process::ExitCode;

use glyphplot::{Budget, FAMILIES};

const HEAD: &str = "// Generated by `mise run build:wasm` (crates/glyphplot/examples/manifest.rs). Do not edit.\n";

/// A budget as budgets.schema.json spells it.
fn budget_json(b: &Budget) -> String {
    format!(r#"{{"gzip":{},"frameMs":{},"worstMs":{},"inputMs":{}}}"#, b.gzip, b.frame_ms, b.worst_ms, b.input_ms)
}

/// `web/pkg/budgets.json`, and modules.js's `budgets`: each module's budget.
fn budgets_json() -> String {
    let entries: Vec<String> = FAMILIES.iter().map(|f| format!("  \"{}\": {}", f.name, budget_json(&f.budget))).collect();
    format!("{{\n{}\n}}\n", entries.join(",\n"))
}

fn modules_js() -> String {
    let imports: Vec<String> = FAMILIES.iter().map(|f| format!("  \"{0}\": () => import(\"./{0}/glyphplot.js\"),\n", f.name)).collect();
    format!(
        "{HEAD}export const charts = [];\nexport const modules = {{}};\nexport const fallback = null;\nexport const budgets = {};\nexport const imports = {{\n{}}};\n",
        budgets_json().trim_end(),
        imports.concat()
    )
}

fn modules_d_ts() -> String {
    format!(
        "{HEAD}export interface Budget {{\n  gzip: number;\n  frameMs: number;\n  worstMs: number;\n  inputMs: number;\n}}\n\
         export declare const charts: readonly unknown[];\n\
         export declare const modules: Readonly<Record<string, string>>;\n\
         export declare const fallback: string | null;\n\
         export declare const budgets: Readonly<Record<string, Budget>>;\n\
         export declare const imports: Readonly<Record<string, () => Promise<unknown>>>;\n"
    )
}

fn write(dir: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dir)?;
    std::fs::write(dir.join("modules.js"), modules_js())?;
    std::fs::write(dir.join("modules.d.ts"), modules_d_ts())?;
    std::fs::write(dir.join("budgets.json"), budgets_json())
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.iter().map(String::as_str).collect::<Vec<_>>().as_slice() {
        ["families"] => {
            FAMILIES.iter().for_each(|f| println!("{}", f.name));
            ExitCode::SUCCESS
        }
        ["write", dir] => match write(Path::new(dir)) {
            Ok(()) => ExitCode::SUCCESS,
            Err(e) => {
                eprintln!("manifest: writing {dir}: {e}");
                ExitCode::FAILURE
            }
        },
        _ => {
            eprintln!("usage: manifest families | manifest write <dir>");
            ExitCode::from(2)
        }
    }
}

//! The manifest `mise run build:wasm` builds from and writes beside the
//! modules (REQ-BUILD-030, REQ-MANIFEST-010, `spec/schemas/manifest.schema.json`).
//!
//! ```sh
//! cargo run -q -p glyphplot --example manifest -- families              # one family a line
//! cargo run -q -p glyphplot --example manifest -- write <dir>           # modules.js, modules.d.ts, budgets.json
//! cargo run -q -p glyphplot --example manifest -- write <dir> --debug   # the debug build's: every type to `all`
//! ```
//!
//! `charts` is every type's meta in registry order and `modules` maps each
//! type to its family's module, which plays exactly the types the manifest
//! gives it; `imports` imports each module's glue and `wasm` gives the URL of
//! its `glyphplot_bg.wasm` as a literal `new URL(…, import.meta.url)`, so the
//! shell fetches it alongside the glue and a bundler emits it once, the file
//! the glue names too; `fallback` is `null`. The debug build maps every type to `all`
//! and falls back to it (REQ-MANIFEST-020).

use std::path::Path;
use std::process::ExitCode;

use glyphplot::registry::{metas, FAMILIES};
use glyphplot::Budget;

const HEAD: &str = "// Generated by `mise run build:wasm` (crates/glyphplot/examples/manifest.rs). Do not edit.\n";

/// The module of the debug build, which plays every type.
const ALL: &str = "all";

/// A budget as budgets.schema.json spells it.
fn budget_json(b: &Budget) -> String {
    serde_json::to_string(b).unwrap_or_default()
}

/// `web/pkg/budgets.json`, and modules.js's `budgets`: each module's budget;
/// in the debug build the one module `all`, with the default budget.
fn budgets_json(debug: bool) -> String {
    let entries: Vec<String> = if debug {
        vec![format!("  \"{ALL}\": {}", budget_json(&Budget::DEFAULT))]
    } else {
        FAMILIES.iter().map(|f| format!("  \"{}\": {}", f.name, budget_json(&f.budget))).collect()
    };
    format!("{{\n{}\n}}\n", entries.join(",\n"))
}

/// `charts`: every type's meta, in registry order.
fn charts_json() -> String {
    let metas: Vec<String> = metas().map(|m| format!("  {}", m.to_json())).collect();
    if metas.is_empty() {
        "[]".into()
    } else {
        format!("[\n{}\n]", metas.join(",\n"))
    }
}

/// `modules`: each type to the module that plays it.
fn modules_json(debug: bool) -> String {
    let entries: Vec<String> =
        FAMILIES.iter().flat_map(|f| f.charts.iter().map(move |e| format!("  \"{}\": \"{}\"", e.meta.slug, if debug { ALL } else { f.name }))).collect();
    if entries.is_empty() {
        "{}".into()
    } else {
        format!("{{\n{}\n}}", entries.join(",\n"))
    }
}

fn modules_js(debug: bool) -> String {
    let names: Vec<&str> = if debug { vec![ALL] } else { FAMILIES.iter().map(|f| f.name).collect() };
    let imports: Vec<String> = names.iter().map(|n| format!("  \"{n}\": () => import(\"./{n}/glyphplot.js\"),\n")).collect();
    // A literal `new URL`, the one form bundlers rewrite and emit (Vite, webpack 5, Parcel).
    let wasm: Vec<String> = names.iter().map(|n| format!("  \"{n}\": () => new URL(\"./{n}/glyphplot_bg.wasm\", import.meta.url),\n")).collect();
    let fallback = if debug { format!("\"{ALL}\"") } else { "null".into() };
    format!(
        "{HEAD}export const charts = {};\nexport const modules = {};\nexport const fallback = {fallback};\nexport const budgets = {};\nexport const imports = {{\n{}}};\nexport const wasm = {{\n{}}};\n",
        charts_json(),
        modules_json(debug),
        budgets_json(debug).trim_end(),
        imports.concat(),
        wasm.concat()
    )
}

/// `modules.d.ts`: the types of modules.js's exports, `Meta` as
/// meta.schema.json and web/src/api.ts give it.
fn modules_d_ts() -> String {
    format!(
        "{HEAD}export interface Budget {{\n  gzip: number;\n  frameMs: number;\n  worstMs: number;\n  inputMs: number;\n}}\n\
         export interface Meta {{\n  slug: string;\n  name: string;\n  note: string;\n  family: string;\n  modes: string[];\n  shapes: string[];\n  \
         options: Record<string, unknown> | null;\n  min: {{ cols: number; rows: number }};\n  drop: string[];\n  mono: string;\n  charset: string;\n  budget: Budget;\n}}\n\
         export declare const charts: readonly Meta[];\n\
         export declare const modules: Readonly<Record<string, string>>;\n\
         export declare const fallback: string | null;\n\
         export declare const budgets: Readonly<Record<string, Budget>>;\n\
         export declare const imports: Readonly<Record<string, () => Promise<unknown>>>;\n\
         export declare const wasm: Readonly<Record<string, () => URL>>;\n"
    )
}

fn write(dir: &Path, debug: bool) -> std::io::Result<()> {
    std::fs::create_dir_all(dir)?;
    std::fs::write(dir.join("modules.js"), modules_js(debug))?;
    std::fs::write(dir.join("modules.d.ts"), modules_d_ts())?;
    std::fs::write(dir.join("budgets.json"), budgets_json(debug))
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let (dir, debug) = match args.iter().map(String::as_str).collect::<Vec<_>>().as_slice() {
        ["families"] => {
            FAMILIES.iter().for_each(|f| println!("{}", f.name));
            return ExitCode::SUCCESS;
        }
        ["write", dir] => (dir.to_string(), false),
        ["write", dir, "--debug"] => (dir.to_string(), true),
        _ => {
            eprintln!("usage: manifest families | manifest write <dir> [--debug]");
            return ExitCode::from(2);
        }
    };
    match write(Path::new(&dir), debug) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("manifest: writing {dir}: {e}");
            ExitCode::FAILURE
        }
    }
}
